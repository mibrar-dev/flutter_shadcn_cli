part of 'installer.dart';

extension InstallerPlatformAliasPart on Installer {
  Future<void> _applyPlatformInstructions(Component component) async {
    await _ensureConfigLoaded();
    await _platformService.applyInstructions(component, config: _cachedConfig);
  }

  void _reportPostInstall(Component component) {
    _platformService.reportPostInstall(component);
  }

  Future<void> generateAliases() async {
    logger.progress('Regenerating app component aliases');
    await _ensureConfigLoaded();
    final config = _cachedConfig ?? const ShadcnConfig();
    final prefix = config.classPrefix;
    final componentsDir = Directory(
      _resolveProjectPath(p.join(_installPath(config), 'components')),
    );
    if (!componentsDir.existsSync()) {
      return;
    }

    final aliases = <String, InstallerAliasEntry>{};
    final imports = <String>{};
    final componentDirs = <String>{};
    for (final entity in componentsDir.listSync(recursive: true)) {
      if (entity is! Directory) {
        continue;
      }
      final name = p.basename(entity.path);
      final mainFile = File(p.join(entity.path, '$name.dart'));
      if (mainFile.existsSync()) {
        componentDirs.add(entity.path);
      }
    }

    // Scan in sorted order so duplicate ownership is deterministic: the
    // alphabetically first export wins and later exports hide the name.
    final sortedDirs = componentDirs.toList()..sort();
    final declarationOwners = <String, String>{};
    final exportHides = <String, Set<String>>{};
    final duplicateOwners = <String, Set<String>>{};
    for (final dirPath in sortedDirs) {
      final componentDir = Directory(dirPath);
      final componentName = p.basename(componentDir.path);
      final mainFile = File(p.join(componentDir.path, '$componentName.dart'));
      if (!mainFile.existsSync()) {
        continue;
      }
      final relativeDir = p.relative(
        componentDir.path,
        from: p.join(targetDir, _installPath(config)),
      );
      final importPath =
          p.join(relativeDir, '$componentName.dart').replaceAll('\\', '/');
      imports.add(importPath);
      // Scan the whole library: the main file plus its parts plus every
      // relatively exported file (transitively). Components like button
      // export their implementation instead of part-ing it, so a parts-only
      // scan misses declarations such as IconButton/TextButton and the
      // barrel silently reintroduces ambiguous imports.
      final scan = _scanComponentLibrary(
        componentDirPath: componentDir.path,
        mainFileName: '$componentName.dart',
      );
      for (final entry in scan.declarations.entries) {
        final className = entry.key;
        final typeParams = entry.value;
        if (typeParams != null) {
          aliases.putIfAbsent(
            className,
            () => InstallerAliasEntry(className, typeParams),
          );
        } else if (!aliases.containsKey(className)) {
          aliases[className] = InstallerAliasEntry(className, null);
        }
      }
      // Track every public declaration (class, enum, mixin, typedef). When
      // two component libraries declare the same name, exporting both
      // produces duplicate-symbol errors for barrel importers, so the later
      // export hides the name. This covers cases like form/autocomplete vs
      // form/text_field both declaring AutoComplete.
      for (final declaration in scan.declarations.keys) {
        final owner = declarationOwners[declaration];
        if (owner == null) {
          declarationOwners[declaration] = importPath;
        } else if (owner != importPath) {
          exportHides
              .putIfAbsent(importPath, () => <String>{})
              .add(declaration);
          duplicateOwners
              .putIfAbsent(declaration, () => <String>{})
              .addAll([owner, importPath]);
        }
      }
      // Component top-level functions colliding with material (e.g. the
      // dialog library's showDialog vs material's showDialog) get the same
      // treatment: hide them on the component export so the barrel stays
      // unambiguous. Material keeps the name.
      for (final function in scan.materialFunctions) {
        exportHides.putIfAbsent(importPath, () => <String>{}).add(function);
        duplicateOwners.putIfAbsent(function, () => <String>{}).addAll(
          ['package:flutter/material.dart', importPath],
        );
      }
    }
    if (duplicateOwners.isNotEmpty) {
      final details = duplicateOwners.entries.toList()
        ..sort((a, b) => a.key.compareTo(b.key));
      for (final entry in details) {
        final owners = entry.value.toList()..sort();
        logger.warn(
          'Duplicate declaration "${entry.key}" exported by '
          '${owners.join(' and ')}; hiding it on later exports in '
          'app_components.dart.',
        );
      }
    }

    final output = StringBuffer()
      ..writeln('// Generated by flutter_shadcn. Do not edit by hand.')
      ..writeln('');
    final hiddenMaterialNames = _materialNamesToHide(
      aliases.values.map((entry) => entry.className),
    );
    if (hiddenMaterialNames.isNotEmpty) {
      output.writeln("export 'package:flutter/material.dart' hide");
      for (var i = 0; i < hiddenMaterialNames.length; i += 1) {
        final suffix = i == hiddenMaterialNames.length - 1 ? ';' : ',';
        output.writeln('    ${hiddenMaterialNames[i]}$suffix');
      }
      output.writeln('');
    }
    final sortedImports = imports.toList()..sort();
    for (final importPath in sortedImports) {
      final hides = (exportHides[importPath]?.toList() ?? <String>[])..sort();
      if (hides.isEmpty) {
        output.writeln("export '$importPath';");
      } else {
        // Trailing-combinator syntax matters: every name but the last gets a
        // comma and the statement ends with ';'. A missing comma here makes
        // Dart misparse every export that follows.
        output.writeln("export '$importPath' hide ${hides.join(', ')};");
      }
    }
    if (prefix != null && prefix.isNotEmpty) {
      output.writeln('');
      for (final importPath in sortedImports) {
        output.writeln("import '$importPath';");
      }
      output.writeln('');
      final aliasEntries = aliases.entries.toList()
        ..sort((a, b) => a.key.compareTo(b.key));
      for (final entry in aliasEntries) {
        final className = entry.value.className;
        final aliasName = '$prefix$className';
        final typeParams = entry.value.typeParams;
        if (typeParams == null || typeParams.isEmpty) {
          output.writeln('typedef $aliasName = $className;');
        } else {
          final typeArgs = _typeArgsFromParams(typeParams);
          output
              .writeln('typedef $aliasName$typeParams = $className$typeArgs;');
        }
      }
    }

    final outputFile = File(
      _resolveProjectPath(p.join(_installPath(config), 'app_components.dart')),
    );
    await outputFile.writeAsString(output.toString());
  }

