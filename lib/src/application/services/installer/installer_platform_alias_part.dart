final _aliasEnumRegex = RegExp(
  r'^\s*enum\s+([A-Z]\w*)',
  multiLine: true,
);

final _aliasMixinRegex = RegExp(
  r'^\s*mixin\s+([A-Z]\w*)',
  multiLine: true,
);

final _aliasTypedefRegex = RegExp(
  r'^\s*typedef\s+([A-Z]\w*)\s*=',
  multiLine: true,
);

final _aliasExportRegex = RegExp(
  r'''export\s+['"]([^'"]+)['"]\s*([^;]*);''',
);

final _partOfRegex = RegExp(
  r'''^\s*part\s+of\s+(?:['"]([^'"]+)['"]\s*;|[A-Za-z_]\w*(?:\s*\.\s*[A-Za-z_]\w*)*\s*;)''',
  multiLine: true,
);

/// Whether the given file's declarations belong to the scanned library: true
/// for the main file and for files without a `part of` directive, and true
/// for `part of` files whose target resolves to the scanned main file.
bool _belongsToLibrary({
  required String content,
  required String fileDir,
  required String mainPath,
  required bool isMainFile,
}) {
  if (isMainFile) {
    return true;
  }
  final match = _partOfRegex.firstMatch(content);
  if (match == null) {
    return true;
  }
  final target = match.group(1);
  if (target == null || target.isEmpty) {
    // `part of LibraryName;` (named style): the target cannot be resolved
    // to this library, so do not attribute its declarations here.
    return false;
  }
  if (!_isRelativeRef(target)) {
    return false;
  }
  final resolved = p.normalize(p.join(fileDir, target));
  return resolved == mainPath;
}

/// Top-level functions exported by package:flutter/material.dart that a
/// component library may redeclare (today only showDialog).
const _aliasMaterialFunctions = <String>{
  'showDialog',
};

/// A library file queued for scanning, with the show/hide filter accumulated
/// from the chain of export directives that led to it (null show = all
/// names visible).
class _PendingScan {
  final String dir;
  final String path;
  final String content;
  final Set<String>? show;
  final Set<String> hide;

  const _PendingScan({
    required this.dir,
    required this.path,
    required this.content,
    required this.show,
    required this.hide,
  });
}

class _LibraryScan {
  /// Public declaration name -> class type parameters (null for
  /// enum/mixin/typedef or classes without type parameters... note: classes
  /// store their type parameter string, which may itself be null).
  final Map<String, String?> declarations;

  /// Declared top-level functions colliding with known material exports.
  final Set<String> materialFunctions;

  const _LibraryScan({
    required this.declarations,
    required this.materialFunctions,
  });
}

/// Collects every public declaration of a component library: the main file,
/// its parts, and every relatively exported file (transitively). Files that
/// are `part of` another library contribute nothing \u2014 their declarations
/// belong to that other library. Export show/hide combinators are honored so
/// hidden names are never attributed to the component.
_LibraryScan _scanComponentLibrary({
  required String componentDirPath,
  required String mainFileName,
}) {
  final declarations = <String, String?>{};
  final materialFunctions = <String>{};
  final seen = <String>{};
  final mainPath = p.normalize(p.join(componentDirPath, mainFileName));
  final mainFile = File(mainPath);
  if (!mainFile.existsSync()) {
    return _LibraryScan(
      declarations: declarations,
      materialFunctions: materialFunctions,
    );
  }
  final pending = <_PendingScan>[
    _PendingScan(
      dir: componentDirPath,
      path: mainPath,
      content: mainFile.readAsStringSync(),
      show: null,
      hide: const {},
    ),
  ];
  while (pending.isNotEmpty) {
    final current = pending.removeLast();
    if (!seen.add(current.path)) {
      continue;
    }
    final content = current.content;
    // A `part of` file only contributes its declarations when it belongs to
    // the library being scanned (its target resolves to the main file).
    // Otherwise the file belongs to a different library (e.g. a preview
    // part file) and its names must not be attributed here. References are
    // still followed so nothing reachable is missed.
    final belongsToLibrary = _belongsToLibrary(
      content: content,
      fileDir: current.dir,
      mainPath: mainPath,
      isMainFile: current.path == mainPath,
    );
    if (belongsToLibrary) {
      for (final match in _classRegex.allMatches(content)) {
        final name = match.group(2);
        if (name == null ||
            name.startsWith('_') ||
            !_combinatorVisible(name, current.show, current.hide)) {
          continue;
        }
        declarations.putIfAbsent(name, () => match.group(3));
      }
      for (final match in _aliasEnumRegex.allMatches(content)) {
        final name = match.group(1);
        if (name != null &&
            !name.startsWith('_') &&
            _combinatorVisible(name, current.show, current.hide)) {
          declarations.putIfAbsent(name, () => null);
        }
      }
      for (final match in _aliasMixinRegex.allMatches(content)) {
        final name = match.group(1);
        if (name != null &&
            !name.startsWith('_') &&
            _combinatorVisible(name, current.show, current.hide)) {
          declarations.putIfAbsent(name, () => null);
        }
      }
      for (final match in _aliasTypedefRegex.allMatches(content)) {
        final name = match.group(1);
        if (name != null &&
            !name.startsWith('_') &&
            _combinatorVisible(name, current.show, current.hide)) {
          declarations.putIfAbsent(name, () => null);
        }
      }
      for (final function in _materialFunctionDeclarations([content])) {
        if (_combinatorVisible(function, current.show, current.hide)) {
          materialFunctions.add(function);
        }
      }
    }
    for (final part in _partRegex.allMatches(content)) {
      final ref = part.group(1);
      if (ref == null || !_isRelativeRef(ref)) {
        continue;
      }
      final resolved = p.normalize(p.join(current.dir, ref));
      final file = File(resolved);
      if (!file.existsSync()) {
        continue;
      }
      pending.add(
        _PendingScan(
          dir: p.dirname(resolved),
          path: resolved,
          content: file.readAsStringSync(),
          show: current.show,
          hide: current.hide,
        ),
      );
    }
    for (final export in _aliasExportRegex.allMatches(content)) {
      final ref = export.group(1);
      if (ref == null || !_isRelativeRef(ref)) {
        continue;
      }
      final resolved = p.normalize(p.join(current.dir, ref));
      final file = File(resolved);
      if (!file.existsSync()) {
        continue;
      }
      final combinators = export.group(2) ?? '';
      pending.add(
        _PendingScan(
          dir: p.dirname(resolved),
          path: resolved,
          content: file.readAsStringSync(),
          show: _intersectShow(current.show, _parseShow(combinators)),
          hide: {...current.hide, ..._parseHide(combinators)},
        ),
      );
    }
  }
  return _LibraryScan(
    declarations: declarations,
    materialFunctions: materialFunctions,
  );
}

bool _isRelativeRef(String ref) {
  return !ref.startsWith('package:') &&
      !ref.startsWith('dart:') &&
      !ref.contains('://');
}

bool _combinatorVisible(String name, Set<String>? show, Set<String> hide) {
  if (hide.contains(name)) {
    return false;
  }
  return show == null || show.contains(name);
}

Set<String>? _intersectShow(Set<String>? parent, Set<String>? child) {
  if (parent == null) {
    return child;
  }
  if (child == null) {
    return parent;
  }
  return parent.intersection(child);
}

Set<String> _parseCombinatorNames(String combinators, String keyword) {
  final match = RegExp(
    '\\b$keyword\\s+([A-Za-z_]\\w*(?:\\s*,\\s*[A-Za-z_]\\w*)*)',
  ).firstMatch(combinators);
  if (match == null) {
    return const {};
  }
  return match
      .group(1)!
      .split(',')
      .map((entry) => entry.trim())
      .where((entry) => entry.isNotEmpty)
      .toSet();
}

Set<String>? _parseShow(String combinators) {
  final names = _parseCombinatorNames(combinators, 'show');
  // Distinguish "no show clause" (null = everything visible) from an
  // unparseable one by re-checking for the keyword.
  if (names.isEmpty && !combinators.contains(RegExp(r'\bshow\b'))) {
    return null;
  }
  return names;
}

Set<String> _parseHide(String combinators) {
  return _parseCombinatorNames(combinators, 'hide');
}

/// Finds declarations of known material top-level functions in the given
/// file contents, ignoring comment lines so doc references such as
/// "use [showDialog] instead" are not mistaken for declarations.
Set<String> _materialFunctionDeclarations(List<String> contents) {
  final names = <String>{};
  for (final content in contents) {
    for (final line in content.split('\n')) {
      final trimmed = line.trimLeft();
      if (trimmed.startsWith('//') ||
          trimmed.startsWith('*') ||
          trimmed.startsWith('/*')) {
        continue;
      }
      for (final function in _aliasMaterialFunctions) {
        final match = RegExp(
          '\\b$function\\s*(<[^>]*>)?\\s*\\(',
        ).firstMatch(line);
        if (match == null) {
          continue;
        }
        // The text before the name must look like a return type, not a call
        // site: it must contain a type word, and must not be an argument
        // position, assignment, await or return (e.g. `showDialog(` as a
        // bare call, `await showDialog(`, `foo(showDialog)`).
        final prefix = line.substring(0, match.start);
        if (!RegExp(r'\w').hasMatch(prefix) ||
            prefix.contains('(') ||
            prefix.contains('=') ||
            RegExp(r'\b(await|return|yield|assert)\b').hasMatch(prefix)) {
          continue;
        }
        names.add(function);
      }
    }
  }
  return names;
}
